#!/usr/bin/env bash
# Regenerate everything derived from schemas/. CI runs this and fails if the result differs
# from what is committed, so generated code can never drift from the schemas.
set -euo pipefail
cd "$(dirname "$0")/.."

python3 tools/bundle.py > bundle/ld-interfaces.bundle.schema.json

# Rust: typify, no builders. Requires `cargo install cargo-typify --version 0.8.0 --locked`.
cargo typify --no-builder bundle/ld-interfaces.bundle.schema.json -o packages/rust/src/generated.rs
sed -i '1i // @generated by tools/codegen.sh from schemas/. Do not edit.' packages/rust/src/generated.rs

# TypeScript: json-schema-to-typescript, pinned in packages/ts/package.json.
(cd packages/ts && npm ci --silent && node gen.mjs)
