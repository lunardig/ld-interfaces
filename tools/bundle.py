"""Merge all schema files into one self-contained document for code generators.

  python tools/bundle.py > generated/schema/ld-interfaces.bundle.schema.json

Every $defs entry from every file lands in one $defs namespace, and cross-file refs
become local refs. Definition names must therefore be unique across files.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import ld  # noqa: E402

REF = re.compile(r"^(?:[a-z0-9-]+\.schema\.json)?#/\$defs/([A-Za-z0-9_]+)$")


def rewrite(node):
    if isinstance(node, dict):
        if "$ref" in node:
            # Siblings of $ref (usually a local description) make some generators mint a
            # duplicate type. The source schemas keep them; the bundle does not.
            m = REF.match(node["$ref"])
            if not m:
                raise ValueError(f"unsupported $ref {node['$ref']!r}")
            return {"$ref": f"#/$defs/{m.group(1)}"}
        out = {}
        for k, v in node.items():
            if k == "$ref":
                m = REF.match(v)
                if not m:
                    raise ValueError(f"unsupported $ref {v!r}")
                out[k] = f"#/$defs/{m.group(1)}"
            else:
                out[k] = rewrite(v)
        return out
    if isinstance(node, list):
        return [rewrite(v) for v in node]
    return node


def discriminator(body: dict) -> str | None:
    """The property that carries a const tag, if this definition is a tagged-union variant."""
    if body.get("type") != "object":
        return None
    for prop, spec in body.get("properties", {}).items():
        if isinstance(spec, dict) and "const" in spec:
            return prop
    return None


def inline_tagged_unions(defs: dict) -> None:
    """Inline oneOf variants that are $refs to tagged objects.

    Code generators such as typify emit an internally tagged enum (serde `tag = ...`) only
    when the variants are inline. With $ref variants they emit an untagged enum and type
    the const tag loosely, so structurally identical variants become indistinguishable.
    A variant definition that nothing else references is then dropped, so generators do not
    emit it twice.
    """
    inlined: set[str] = set()
    for name, body in defs.items():
        variants = body.get("oneOf")
        if not variants or not all(isinstance(v, dict) and set(v) == {"$ref"} for v in variants):
            continue
        targets = [v["$ref"].rsplit("/", 1)[1] for v in variants]
        tags = {discriminator(defs[t]) for t in targets}
        if len(tags) != 1 or None in tags:
            continue  # not a uniformly tagged union
        body["oneOf"] = [{"title": t, **{k: v for k, v in defs[t].items() if k != "description"}} for t in targets]
        inlined.update(targets)
    still_referenced = set(re.findall(r'"#/\$defs/([A-Za-z0-9_]+)"', json.dumps(defs)))
    for t in inlined - still_referenced:
        del defs[t]


def bundle() -> dict:
    defs: dict = {}
    origin: dict[str, str] = {}
    for name in ld.SCHEMA_FILES:
        for def_name, body in ld.load_json(ld.SCHEMA_DIR / name).get("$defs", {}).items():
            if def_name in defs:
                raise ValueError(f"definition {def_name} appears in both {origin[def_name]} and {name}")
            defs[def_name] = rewrite(body)
            origin[def_name] = name
    inline_tagged_unions(defs)
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": ld.BASE_URI + "ld-interfaces.bundle.schema.json",
        "title": "LdInterfaces",
        "description": "Generated by tools/bundle.py from schemas/. Do not edit.",
        "$defs": dict(sorted(defs.items())),
    }


if __name__ == "__main__":
    json.dump(bundle(), sys.stdout, indent=2)
    sys.stdout.write("\n")
