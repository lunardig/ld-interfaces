// Generates src/generated.ts from the bundled schema. Run via tools/codegen.sh.
import { readFile, writeFile } from "node:fs/promises";
import { compile } from "json-schema-to-typescript";

const schema = JSON.parse(await readFile("../../bundle/ld-interfaces.bundle.schema.json", "utf8"));
const ts = await compile(schema, "LdInterfaces", {
  bannerComment: "// @generated by tools/codegen.sh from schemas/. Do not edit.",
  unreachableDefinitions: true,
  additionalProperties: false,
  strictIndexSignatures: true,
  format: true,
});
await writeFile("src/generated.ts", ts);
